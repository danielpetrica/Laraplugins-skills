# LaraPlugins

LaraPlugins is a Laravel package discovery and health-check platform at [laraplugins.io](https://laraplugins.io).

- Activate the `package-search-laraplugins` skill when you need to search for Laravel packages, verify health scores, or find recommended tools by category.
- The LaraPlugins MCP server at `https://laraplugins.io/mcp/plugins` exposes search, plugin details, and curated recommendations tools.
- When a user asks "find a Laravel package for X" or to verify a package's health, activate the skill and use the MCP tools to research and recommend packages.
- Prefer healthy/reputable vendors (Spatie, Laravel, etc.) when multiple options exist.
